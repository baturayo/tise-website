"""Builds src/data/chartMap.ts, the coastlines of the sea chart at the top of the page.

Clips Natural Earth 1:10m land, minor islands and lakes (public domain, naturalearthdata.com) to two
regions, projects them to Mercator and simplifies them into SVG paths.

Usage:
  mkdir -p /tmp/ne && cd /tmp/ne && for f in ne_10m_land ne_10m_lakes ne_10m_minor_islands; do
    curl -sLO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/$f.geojson; done
  python3 scripts/build-chart-map.py /tmp/ne src/data/chartMap.ts
"""
import json, math, sys

DATA = sys.argv[1]
OUT = sys.argv[2]

def merc(lat):
    return math.log(math.tan(math.pi / 4 + math.radians(lat) / 2))

def clip(ring, bb):
    """Sutherland-Hodgman against a lon/lat rectangle."""
    x0, y0, x1, y1 = bb
    def inter(p, q, edge):
        (px, py), (qx, qy) = p, q
        if edge in ('l', 'r'):
            x = x0 if edge == 'l' else x1
            t = (x - px) / (qx - px)
            return (x, py + t * (qy - py))
        y = y0 if edge == 'b' else y1
        t = (y - py) / (qy - py)
        return (px + t * (qx - px), y)
    inside = {'l': lambda p: p[0] >= x0, 'r': lambda p: p[0] <= x1, 'b': lambda p: p[1] >= y0, 't': lambda p: p[1] <= y1}
    pts = ring
    for e in 'lrbt':
        if not pts: break
        out = []
        for i, cur in enumerate(pts):
            prev = pts[i - 1]
            if inside[e](cur):
                if not inside[e](prev): out.append(inter(prev, cur, e))
                out.append(cur)
            elif inside[e](prev):
                out.append(inter(prev, cur, e))
        pts = out
    return pts

def dp(pts, tol):
    if len(pts) < 3: return pts
    keep = [False] * len(pts); keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (ax, ay), (bx, by) = pts[a], pts[b]
        dx, dy = bx - ax, by - ay
        L = math.hypot(dx, dy) or 1e-9
        best, idx = 0, None
        for i in range(a + 1, b):
            px, py = pts[i]
            d = abs(dy * px - dx * py + bx * ay - by * ax) / L
            if d > best: best, idx = d, i
        if idx is not None and best > tol:
            keep[idx] = True
            stack += [(a, idx), (idx, b)]
    return [p for p, k in zip(pts, keep) if k]

def area(pts):
    return abs(sum(pts[i - 1][0] * p[1] - p[0] * pts[i - 1][1] for i, p in enumerate(pts))) / 2

def rings(path):
    gj = json.load(open(path))
    for f in gj['features']:
        g = f['geometry']
        polys = [g['coordinates']] if g['type'] == 'Polygon' else g['coordinates'] if g['type'] == 'MultiPolygon' else []
        for poly in polys:
            for ring in poly:
                yield ring

def region(name, clipbb, view, width, files, tol=0.5):
    lon0, lat_top = view[0], view[3]
    R = width / math.radians(view[2] - view[0])
    height = R * (merc(view[3]) - merc(view[1]))
    proj = lambda lon, lat: (R * math.radians(lon - lon0), R * (merc(lat_top) - merc(lat)))
    out = {}
    for key, paths in files.items():
        d = []
        for path in paths:
            for ring in rings(path):
                xs = [p[0] for p in ring]; ys = [p[1] for p in ring]
                if max(xs) < clipbb[0] or min(xs) > clipbb[2] or max(ys) < clipbb[1] or min(ys) > clipbb[3]: continue
                c = clip([tuple(p[:2]) for p in ring], clipbb)
                if len(c) < 3: continue
                if c[0] == c[-1]: c = c[:-1]
                # simplify as an open line: its two ends are neighbours on the ring, so they differ
                pts = dp([proj(*p) for p in c], tol)
                if len(pts) < 3 or area(pts) < 3: continue
                d.append('M' + 'L'.join(f'{x:.1f},{y:.1f}' for x, y in pts) + 'Z')
        out[key] = ''.join(d)
    return dict(name=name, lon0=lon0, latTop=lat_top, R=round(R, 3), width=round(width, 1), height=round(height, 1), **out)

land = [f'{DATA}/ne_10m_land.geojson', f'{DATA}/ne_10m_minor_islands.geojson']
lakes = [f'{DATA}/ne_10m_lakes.geojson']
nw = region('nw', (-1.5, 49.0, 10.0, 54.6), (1.9, 50.55, 7.1, 53.0), 1000, {'land': land, 'lakes': lakes})
tr = region('tr', (26.6, 35.8, 29.6, 37.7), (27.45, 36.45, 28.75, 37.1), 600, {'land': land})

ts = ['/* Generated by scripts/build-chart-map.py from Natural Earth (public domain), 1:10m land, minor islands and lakes. Mercator, y down. Do not edit by hand. */',
      'export interface ChartMap { lon0: number; latTop: number; R: number; width: number; height: number; land: string; lakes?: string }']
for m in (nw, tr):
    m = {k: v for k, v in m.items() if k != 'name'}
    ts.append(f"export const {'northSea' if m['lon0'] < 10 else 'aegean'}: ChartMap = {json.dumps(m)};")
open(OUT, 'w').write('\n'.join(ts) + '\n')
print('nw', nw['width'], nw['height'], len(nw['land']), len(nw['lakes']))
print('tr', tr['width'], tr['height'], len(tr['land']))
