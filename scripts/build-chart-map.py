"""Builds src/data/chartMap.ts, the coastlines of the sea chart at the top of the page.

Clips Natural Earth 1:10m land, minor islands and lakes (public domain, naturalearthdata.com) to two
regions, projects them to Mercator and simplifies them into SVG paths.

Usage:
  mkdir -p /tmp/ne && cd /tmp/ne && for f in ne_10m_land ne_10m_lakes ne_10m_minor_islands; do
    curl -sLO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/$f.geojson; done
  python3 scripts/build-chart-map.py /tmp/ne src/data/chartMap.ts
"""
import json, math, sys

DATA = sys.argv[1]
OUT = sys.argv[2]

from chartgeo import merc, clip, dp, area, rings, region

land = [f'{DATA}/ne_10m_land.geojson', f'{DATA}/ne_10m_minor_islands.geojson']
lakes = [f'{DATA}/ne_10m_lakes.geojson']
nw = region('nw', (-1.5, 49.0, 10.0, 54.6), (1.9, 50.55, 7.1, 53.0), 1000, {'land': land, 'lakes': lakes})
tr = region('tr', (26.6, 35.8, 29.6, 37.7), (27.45, 36.45, 28.75, 37.1), 600, {'land': land})

ts = ['/* Generated by scripts/build-chart-map.py from Natural Earth (public domain), 1:10m land, minor islands and lakes. Mercator, y down. Do not edit by hand. */',
      'export interface ChartMap { lon0: number; latTop: number; R: number; width: number; height: number; land: string; lakes?: string }']
for m in (nw, tr):
    m = {k: v for k, v in m.items() if k != 'name'}
    ts.append(f"export const {'northSea' if m['lon0'] < 10 else 'aegean'}: ChartMap = {json.dumps(m)};")
open(OUT, 'w').write('\n'.join(ts) + '\n')
print('nw', nw['width'], nw['height'], len(nw['land']), len(nw['lakes']))
print('tr', tr['width'], tr['height'], len(tr['land']))
