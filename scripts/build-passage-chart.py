"""Builds src/blog/data/passageChart.ts, the chart for the Gibraltar to Las Palmas blog post.

Natural Earth 1:10m (public domain): land, minor islands, and the 200, 1000, 2000, 3000 and 4000 m
depth areas, clipped to the passage from the Strait of Gibraltar to the Canaries, projected to
Mercator and simplified into SVG paths. Each depth path holds everything deeper than its depth; it
has holes (rises and banks), so draw it with fill-rule evenodd.

Usage (same data folder as build-chart-map.py, plus the bathymetry files):
  for f in ne_10m_bathymetry_K_200 ne_10m_bathymetry_J_1000 ne_10m_bathymetry_I_2000 \\
           ne_10m_bathymetry_H_3000 ne_10m_bathymetry_G_4000; do
    curl -sLO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/$f.geojson; done
  python3 scripts/build-passage-chart.py /tmp/ne src/blog/data/passageChart.ts
"""
import json, sys
from chartgeo import region

DATA, OUT = sys.argv[1], sys.argv[2]

DEPTHS = {200: 'K_200', 1000: 'J_1000', 2000: 'I_2000', 3000: 'H_3000', 4000: 'G_4000'}
files = {'land': [f'{DATA}/ne_10m_land.geojson', f'{DATA}/ne_10m_minor_islands.geojson']}
for d, name in DEPTHS.items():
    files[f'd{d}'] = [f'{DATA}/ne_10m_bathymetry_{name}.geojson']

# view: lon west, lat south, lon east, lat north; the clip box is wider so no clipped edge shows
m = region('passage', (-31.0, 21.0, 6.0, 43.5), (-17.2, 27.35, -4.7, 36.85), 1000, files, tol=0.45)

depth = {d: m.pop(f'd{d}') for d in DEPTHS}
m.pop('name')
ts = [
    '/* Generated by scripts/build-passage-chart.py from Natural Earth (public domain): 1:10m land, minor islands and bathymetry. Mercator, y down. Do not edit by hand. */',
    'export interface PassageChart { lon0: number; latTop: number; R: number; width: number; height: number; land: string; depth: Record<200 | 1000 | 2000 | 3000 | 4000, string> }',
    f'export const passageChart: PassageChart = {json.dumps({**m, "depth": depth})};',
]
open(OUT, 'w').write('\n'.join(ts) + '\n')
print('size', m['width'], m['height'], 'land', len(m['land']), {d: len(p) for d, p in depth.items()})
